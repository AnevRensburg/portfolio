#!/usr/bin/env node
/**
 * Converts the site screenshots in images-src/ (<project>-desktop/-full/-mobile.jpg) into AVIF +
 * WebP at a few widths in public/images, and writes the typed manifest <app-picture> reads.
 * Also builds the social preview image and favicons.
 *
 * New screenshots: drop them into images-src/ with the same names and run `npm run images`.
 */
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'images-src');
const outDir = path.join(root, 'public/images');
const manifestFile = path.join(root, 'src/app/data/image-manifest.ts');

/** Target widths per screenshot type. Full-page shots are shown narrow, so stay small. */
const WIDTHS = { desktop: [640, 1100, 1440], full: [560, 900], mobile: [300, 600] };

const manifest = {};
await rm(outDir, { recursive: true, force: true });
await mkdir(path.join(outDir, 'work'), { recursive: true });

for (const file of (await readdir(source)).filter((f) => f.endsWith('.jpg')).sort()) {
  const name = path.basename(file, '.jpg');
  const kind = name.split('-').at(-1);
  const input = path.join(source, file);
  const meta = await sharp(input).metadata();
  const widths = [...new Set(WIDTHS[kind].map((w) => Math.min(w, meta.width)))];
  let height = 0;
  for (const width of widths) {
    const img = sharp(input).resize({ width });
    const out = path.join(outDir, 'work', `${name}-${width}`);
    const info = await img.clone().avif({ quality: 55, effort: 6 }).toFile(`${out}.avif`);
    await img.clone().webp({ quality: 78, effort: 6 }).toFile(`${out}.webp`);
    height = info.height;
  }
  manifest[`work/${name}`] = { width: widths.at(-1), height, widths };
  console.log(`${file.padEnd(28)} -> work/${name} [${widths.join(', ')}]`);
}

// Social preview: navy card with the name, rendered from SVG.
const og = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630">
  <rect width="1200" height="630" fill="#0a1a33"/>
  <rect x="40" y="40" width="1120" height="550" fill="none" stroke="#ffffff" stroke-opacity=".35" stroke-width="2"/>
  <text x="100" y="270" fill="#fff" font-family="Arial, sans-serif" font-size="68" font-weight="700">Ané Janse van Rensburg</text>
  <text x="100" y="350" fill="#c9d4e5" font-family="Arial, sans-serif" font-size="36">Websites for small businesses · Cape Town</text>
  <line x1="100" y1="410" x2="300" y2="410" stroke="#fff" stroke-width="3"/>
</svg>`;
await sharp(Buffer.from(og)).jpeg({ quality: 82, mozjpeg: true }).toFile(path.join(outDir, 'og-image.jpg'));

// Favicons: "AJ" monogram, white on navy.
const icon = (size) =>
  sharp(
    Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64">
      <rect width="64" height="64" rx="12" fill="#0a1a33"/>
      <rect x="5" y="5" width="54" height="54" rx="8" fill="none" stroke="#fff" stroke-opacity=".5" stroke-width="2"/>
      <text x="32" y="42" text-anchor="middle" fill="#fff" font-family="Arial, sans-serif" font-size="26" font-weight="700">AJ</text>
    </svg>`),
  )
    .resize(size, size)
    .png({ compressionLevel: 9 });
await icon(48).toFile(path.join(root, 'public/favicon.png'));
await icon(180).toFile(path.join(root, 'public/apple-touch-icon.png'));

await writeFile(
  manifestFile,
  `// Generated by scripts/optimize-images.mjs. Do not edit by hand.\n\n` +
    `export interface ImageEntry {\n  /** Intrinsic width of the largest generated file. */\n  readonly width: number;\n  readonly height: number;\n  /** Widths generated as <name>-<width>.avif / .webp. */\n  readonly widths: readonly number[];\n}\n\n` +
    `export const IMAGE_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, ImageEntry>;\n\n` +
    `export type ImageKey = keyof typeof IMAGE_MANIFEST;\n`,
);
